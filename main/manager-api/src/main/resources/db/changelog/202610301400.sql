-- B2 execution is additive. Existing ledgers and account data are preserved.
CREATE TABLE ai_run (
 id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 list_sequence BIGINT NOT NULL AUTO_INCREMENT UNIQUE,
 conversation_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_message_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 output_message_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 control_epoch BIGINT NOT NULL,
 attempt INT NOT NULL DEFAULT 0,
 status VARCHAR(16) NOT NULL DEFAULT 'queued',
 lease_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_owner VARCHAR(128) NULL,
 lease_expires_at DATETIME(3) NULL,
 last_chunk_sequence BIGINT NOT NULL DEFAULT 0,
 last_chunk_hash CHAR(64) NULL,
 output_text LONGTEXT NOT NULL,
 model VARCHAR(128) NOT NULL,
 error_code VARCHAR(64) NULL,
 usage_json LONGTEXT NULL,
 provider_request_id VARCHAR(200) NULL,
 finish_reason VARCHAR(32) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 active_slot TINYINT GENERATED ALWAYS AS (CASE WHEN status IN ('queued','running','streaming') THEN 1 ELSE NULL END) STORED,
 UNIQUE KEY uk_ai_run_active(conversation_id,active_slot),
 UNIQUE KEY uk_ai_run_output(output_message_id),
 INDEX idx_ai_run_claim(status,lease_expires_at,list_sequence),
 INDEX idx_ai_run_list(conversation_id,list_sequence),
 CONSTRAINT fk_ai_run_conversation FOREIGN KEY(conversation_id) REFERENCES ai_conversation(id),
 CONSTRAINT fk_ai_run_input FOREIGN KEY(input_message_id) REFERENCES ai_message(id),
 CONSTRAINT fk_ai_run_output FOREIGN KEY(output_message_id) REFERENCES ai_message(id),
 CONSTRAINT chk_ai_run_status CHECK (status IN ('queued','running','streaming','completed','failed','canceled')),
 CONSTRAINT chk_ai_run_attempt CHECK (attempt BETWEEN 0 AND 3),
 CONSTRAINT chk_ai_run_usage CHECK (usage_json IS NULL OR JSON_VALID(usage_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE ai_model_usage (
 run_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 attempt INT NOT NULL,
 model VARCHAR(128) NOT NULL,
 input_tokens BIGINT NOT NULL,
 output_tokens BIGINT NOT NULL,
 total_tokens BIGINT NOT NULL,
 provider_request_id VARCHAR(200) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(run_id,attempt),
 CONSTRAINT fk_ai_usage_run FOREIGN KEY(run_id) REFERENCES ai_run(id),
 CONSTRAINT chk_ai_usage_tokens CHECK (input_tokens>=0 AND output_tokens>=0 AND total_tokens>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
