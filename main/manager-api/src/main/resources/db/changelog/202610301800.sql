-- B3 is additive. Evidence and business rows are never deleted by this module.
CREATE TABLE ai_attachment (
 id BIGINT PRIMARY KEY,
 conversation_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 uploader_user_id BIGINT NOT NULL,
 client_upload_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 filename VARCHAR(255) NOT NULL,
 mime_type VARCHAR(80) NOT NULL,
 kind VARCHAR(16) NOT NULL,
 size BIGINT NOT NULL,
 sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending_upload',
 original_object_id BIGINT NULL,
 linked_message_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 linked_seq BIGINT NULL,
 metadata_json LONGTEXT NOT NULL,
 error_code VARCHAR(64) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 expires_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_attachment_upload(uploader_user_id,client_upload_id),
 INDEX idx_attachment_expiry(status,expires_at),
 CONSTRAINT fk_attachment_conversation FOREIGN KEY(conversation_id) REFERENCES ai_conversation(id),
 CONSTRAINT fk_attachment_message FOREIGN KEY(linked_message_id) REFERENCES ai_message(id),
 CONSTRAINT chk_attachment_status CHECK(status IN ('pending_upload','uploaded','processing','ready','failed','expired')),
 CONSTRAINT chk_attachment_metadata CHECK(JSON_VALID(metadata_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE ai_media_job (
 id BIGINT PRIMARY KEY,
 attachment_id BIGINT NOT NULL,
 job_type VARCHAR(32) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'queued',
 attempt INT NOT NULL DEFAULT 0,
 lease_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_owner VARCHAR(128) NULL,
 lease_expires_at DATETIME(3) NULL,
 error_code VARCHAR(64) NULL,
 metadata_json LONGTEXT NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_attachment_job(attachment_id,job_type),
 INDEX idx_media_claim(status,lease_expires_at,created_at),
 CONSTRAINT fk_media_attachment FOREIGN KEY(attachment_id) REFERENCES ai_attachment(id),
 CONSTRAINT chk_media_attempt CHECK(attempt BETWEEN 0 AND 3),
 CONSTRAINT chk_media_status CHECK(status IN ('queued','running','completed','failed')),
 CONSTRAINT chk_media_metadata CHECK(JSON_VALID(metadata_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE ai_attachment_object (
 id BIGINT PRIMARY KEY,
 attachment_id BIGINT NOT NULL,
 job_id BIGINT NULL,
 attempt INT NULL,
 variant VARCHAR(24) NOT NULL,
 storage_key VARCHAR(300) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'reserved',
 size BIGINT NOT NULL,
 sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 mime_type VARCHAR(80) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 expires_at DATETIME(3) NOT NULL,
 UNIQUE KEY uk_attachment_object_key(storage_key),
 INDEX idx_attachment_object_gc(status,expires_at),
 CONSTRAINT fk_object_attachment FOREIGN KEY(attachment_id) REFERENCES ai_attachment(id),
 CONSTRAINT fk_object_job FOREIGN KEY(job_id) REFERENCES ai_media_job(id),
 CONSTRAINT chk_object_status CHECK(status IN ('reserved','stored','referenced','abandoned','deleting','deleted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE ai_attachment_artifact (
 attachment_id BIGINT NOT NULL,
 variant VARCHAR(24) NOT NULL,
 object_id BIGINT NOT NULL,
 job_id BIGINT NOT NULL,
 attempt INT NOT NULL,
 PRIMARY KEY(attachment_id,variant),
 UNIQUE KEY uk_attachment_artifact_object(object_id),
 CONSTRAINT fk_artifact_attachment FOREIGN KEY(attachment_id) REFERENCES ai_attachment(id),
 CONSTRAINT fk_artifact_object FOREIGN KEY(object_id) REFERENCES ai_attachment_object(id),
 CONSTRAINT fk_artifact_job FOREIGN KEY(job_id) REFERENCES ai_media_job(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
