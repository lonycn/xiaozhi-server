-- B4 immutable snapshots. No historical changeset, source object, or business row is overwritten/deleted.
CREATE TABLE support_frame (
 id BIGINT PRIMARY KEY,
 conversation_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 creator_user_id BIGINT NOT NULL,
 client_frame_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_attachment_id BIGINT NOT NULL,
 frame_attachment_id BIGINT NOT NULL,
 requested_time_ms BIGINT NULL,
 actual_time_ms BIGINT NULL,
 capture_policy VARCHAR(24) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_frame_client(creator_user_id,client_frame_id),
 UNIQUE KEY uk_frame_attachment(frame_attachment_id),
 INDEX idx_frame_conversation(conversation_id,id),
 CONSTRAINT fk_frame_conversation FOREIGN KEY(conversation_id) REFERENCES ai_conversation(id),
 CONSTRAINT fk_frame_source FOREIGN KEY(source_attachment_id) REFERENCES ai_attachment(id),
 CONSTRAINT fk_frame_output FOREIGN KEY(frame_attachment_id) REFERENCES ai_attachment(id),
 CONSTRAINT chk_frame_time CHECK(requested_time_ms IS NULL OR requested_time_ms>=0),
 CONSTRAINT chk_frame_actual CHECK(actual_time_ms IS NULL OR actual_time_ms>=0),
 CONSTRAINT chk_frame_policy CHECK(capture_policy='first_at_or_after')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_annotation (
 id BIGINT PRIMARY KEY,
 conversation_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 creator_user_id BIGINT NOT NULL,
 client_annotation_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 frame_id BIGINT NOT NULL,
 label VARCHAR(200) NOT NULL,
 format VARCHAR(24) NOT NULL,
 scene_json LONGTEXT NOT NULL,
 scene_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 render_attachment_id BIGINT NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY uk_annotation_client(creator_user_id,client_annotation_id),
 UNIQUE KEY uk_annotation_attachment(render_attachment_id),
 INDEX idx_annotation_list(conversation_id,id),
 CONSTRAINT fk_annotation_conversation FOREIGN KEY(conversation_id) REFERENCES ai_conversation(id),
 CONSTRAINT fk_annotation_frame FOREIGN KEY(frame_id) REFERENCES support_frame(id),
 CONSTRAINT fk_annotation_render FOREIGN KEY(render_attachment_id) REFERENCES ai_attachment(id),
 CONSTRAINT chk_annotation_format CHECK(format='annotation-v1'),
 CONSTRAINT chk_annotation_scene CHECK(JSON_VALID(scene_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
