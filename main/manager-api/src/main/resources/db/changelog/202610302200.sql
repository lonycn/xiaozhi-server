-- B5 additive business media generations. No existing room, table, row or object is cleared.
CREATE TABLE support_media_session (
 id BIGINT PRIMARY KEY,
 conversation_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 assignment_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 customer_user_id BIGINT NOT NULL,
 agent_user_id BIGINT NOT NULL,
 inviter_user_id BIGINT NOT NULL,
 invitee_user_id BIGINT NOT NULL,
 client_session_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 mode VARCHAR(8) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'invited',
 control_epoch BIGINT NOT NULL DEFAULT 1,
 current_generation INT NOT NULL DEFAULT 1,
 next_generation INT NOT NULL DEFAULT 2,
 cleanup_status VARCHAR(16) NOT NULL DEFAULT 'not_required',
 error_code VARCHAR(64) NULL,
 expires_at DATETIME(3) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 ended_at DATETIME(3) NULL,
 active_slot TINYINT GENERATED ALWAYS AS(CASE WHEN status IN ('invited','connecting','active','reconnecting','ending') THEN 1 ELSE NULL END) STORED,
 UNIQUE KEY uk_media_session_client(inviter_user_id,client_session_id),
 UNIQUE KEY uk_media_session_active(conversation_id,active_slot),
 INDEX idx_media_session_maintenance(status,id),
 CONSTRAINT fk_media_session_conversation FOREIGN KEY(conversation_id) REFERENCES ai_conversation(id),
 CONSTRAINT fk_media_session_request FOREIGN KEY(request_id) REFERENCES support_request(id),
 CONSTRAINT fk_media_session_assignment FOREIGN KEY(assignment_id) REFERENCES support_assignment(id),
 CONSTRAINT chk_media_mode CHECK(mode IN ('audio','video')),
 CONSTRAINT chk_media_session_status CHECK(status IN ('invited','connecting','active','reconnecting','ending','ended','rejected','canceled','expired','failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_media_room (
 id BIGINT PRIMARY KEY,
 session_id BIGINT NOT NULL,
 generation INT NOT NULL,
 room_name VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 livekit_sid VARCHAR(100) NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'preparing',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 retired_at DATETIME(3) NULL,
 last_polled_at DATETIME(3) NULL,
 UNIQUE KEY uk_media_room_generation(session_id,generation),
 UNIQUE KEY uk_media_room_name(room_name),
 CONSTRAINT fk_media_room_session FOREIGN KEY(session_id) REFERENCES support_media_session(id),
 CONSTRAINT chk_media_room_generation CHECK(generation>0),
 CONSTRAINT chk_media_room_status CHECK(status IN ('preparing','ready','active','retired','cleanup_pending','cleaned'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_media_member (
 id BIGINT PRIMARY KEY,
 session_id BIGINT NOT NULL,
 room_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 role VARCHAR(16) NOT NULL,
 identity VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'invited',
 reservation_status VARCHAR(24) NOT NULL DEFAULT 'reserved',
 consent_microphone TINYINT NOT NULL DEFAULT 0,
 consent_camera TINYINT NOT NULL DEFAULT 0,
 consent_snapshots TINYINT NOT NULL DEFAULT 0,
 consent_hash CHAR(64) NULL,
 consented_at DATETIME(3) NULL,
 participant_sid VARCHAR(100) NULL,
 peer_sid VARCHAR(100) NULL,
 ready_at DATETIME(3) NULL,
 receiving_audio TINYINT NOT NULL DEFAULT 0,
 receiving_video TINYINT NOT NULL DEFAULT 0,
 last_seen_at DATETIME(3) NULL,
 revoked_at DATETIME(3) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 media_busy_slot TINYINT GENERATED ALWAYS AS(CASE WHEN role='agent' AND reservation_status IN ('reserved','held','cleanup_pending') THEN 1 ELSE NULL END) STORED,
 UNIQUE KEY uk_media_member_actor(room_id,user_id),
 UNIQUE KEY uk_media_member_identity(identity),
 UNIQUE KEY uk_media_agent_busy(user_id,media_busy_slot),
 CONSTRAINT fk_media_member_session FOREIGN KEY(session_id) REFERENCES support_media_session(id),
 CONSTRAINT fk_media_member_room FOREIGN KEY(room_id) REFERENCES support_media_room(id),
 CONSTRAINT chk_media_member_role CHECK(role IN ('customer','agent')),
 CONSTRAINT chk_media_member_status CHECK(status IN ('invited','accepted','active','left','revoked')),
 CONSTRAINT chk_media_reservation CHECK(reservation_status IN ('reserved','held','cleanup_pending','released'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_media_transfer (
 id BIGINT PRIMARY KEY,
 session_id BIGINT NOT NULL,
 requester_user_id BIGINT NOT NULL,
 source_assignment_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source_generation INT NOT NULL,
 target_generation INT NOT NULL,
 target_agent_user_id BIGINT NOT NULL,
 client_transfer_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 control_epoch BIGINT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'invited',
 customer_approved_at DATETIME(3) NULL,
 target_accepted_at DATETIME(3) NULL,
 error_code VARCHAR(64) NULL,
 expires_at DATETIME(3) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 completed_at DATETIME(3) NULL,
 active_slot TINYINT GENERATED ALWAYS AS(CASE WHEN status IN ('invited','preparing','ready','committing') THEN 1 ELSE NULL END) STORED,
 UNIQUE KEY uk_media_transfer_client(requester_user_id,client_transfer_id),
 UNIQUE KEY uk_media_transfer_active(session_id,active_slot),
 INDEX idx_media_transfer_reservation(target_agent_user_id,status),
 CONSTRAINT fk_media_transfer_session FOREIGN KEY(session_id) REFERENCES support_media_session(id),
 CONSTRAINT fk_media_transfer_source FOREIGN KEY(source_assignment_id) REFERENCES support_assignment(id),
 CONSTRAINT chk_media_transfer_status CHECK(status IN ('invited','preparing','ready','committing','completed','rejected','canceled','expired','failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_media_outbox (
 id BIGINT PRIMARY KEY,
 session_id BIGINT NOT NULL,
 room_id BIGINT NOT NULL,
 transfer_id BIGINT NULL,
 kind VARCHAR(24) NOT NULL,
 identity VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 intent_key VARCHAR(220) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 control_epoch BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'queued',
 attempt INT NOT NULL DEFAULT 0,
 lease_token VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_expires_at DATETIME(3) NULL,
 available_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 error_code VARCHAR(64) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 completed_at DATETIME(3) NULL,
 UNIQUE KEY uk_media_outbox_intent(intent_key),
 INDEX idx_media_outbox_claim(status,available_at,id),
 CONSTRAINT fk_media_outbox_session FOREIGN KEY(session_id) REFERENCES support_media_session(id),
 CONSTRAINT fk_media_outbox_room FOREIGN KEY(room_id) REFERENCES support_media_room(id),
 CONSTRAINT fk_media_outbox_transfer FOREIGN KEY(transfer_id) REFERENCES support_media_transfer(id),
 CONSTRAINT chk_media_outbox_kind CHECK(kind IN ('create_room','remove_participant','delete_room')),
 CONSTRAINT chk_media_outbox_status CHECK(status IN ('queued','running','done','obsolete'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE support_media_webhook (
 event_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 body_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 session_id BIGINT NULL,
 room_id BIGINT NULL,
 event_type VARCHAR(64) NOT NULL,
 result VARCHAR(32) NOT NULL,
 received_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 CONSTRAINT fk_media_webhook_session FOREIGN KEY(session_id) REFERENCES support_media_session(id),
 CONSTRAINT fk_media_webhook_room FOREIGN KEY(room_id) REFERENCES support_media_room(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
